-- content_hash o url puede ser NULL (tenor/giphy no tienen hash; legacy sin
-- hash). SQLite toleraba NULL dentro de la PRIMARY KEY; PostgreSQL no, así que
-- la unicidad va por un índice sobre COALESCE en vez de PK.
CREATE TABLE IF NOT EXISTS gif_blocklist (
    guild_id BIGINT NOT NULL,
    content_hash TEXT,
    url TEXT,
    blocked_at TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_gif_blocklist
    ON gif_blocklist (guild_id, COALESCE(content_hash, ''), COALESCE(url, ''));
CREATE INDEX IF NOT EXISTS idx_gif_blocklist_guild_hash ON gif_blocklist (guild_id, content_hash);
CREATE INDEX IF NOT EXISTS idx_gif_blocklist_guild_url ON gif_blocklist (guild_id, url);

