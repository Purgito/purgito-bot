-- Esquema PostgreSQL de Purgito. Generado desde la SQLite de producción
-- (misma forma de columnas) y luego mantenido a mano. Idempotente: todo es
-- IF NOT EXISTS, se aplica en cada arranque (db.init_db).

-- Los timestamps de Purgito son TEXT 'YYYY-MM-DD HH24:MI:SS' en UTC (formato
-- heredado de SQLite, que el código compara como string). utc_now() es el "ahora"
-- en ese formato; los DEFAULT de abajo lo inlinean.
CREATE OR REPLACE FUNCTION utc_now() RETURNS text
    LANGUAGE sql STABLE PARALLEL SAFE
    AS $$ SELECT to_char(timezone('utc', now()), 'YYYY-MM-DD HH24:MI:SS') $$;

-- t + delta, en el mismo formato texto, o NULL si `t` no es una fecha válida (o
-- la suma se sale de rango). SQLite devolvía NULL con una fecha malformada y la
-- fila simplemente no cumplía la condición; el cast `::timestamp` de PostgreSQL
-- en cambio aborta la query ENTERA (y con ella a todo el scheduler). Esta
-- función conserva el comportamiento de SQLite: una fila inválida da NULL y las
-- demás siguen. Las queries de vencimiento deciden qué hacer con ese NULL.
-- Un año de 5 dígitos (la suma cruzó el 9999) también es NULL: como texto
-- "10000-01-01" ordenaría ANTES que "2026-..." y parecería vencido.
CREATE OR REPLACE FUNCTION utc_text_plus(t text, delta interval) RETURNS text
    LANGUAGE plpgsql STABLE PARALLEL SAFE
    AS $$
DECLARE
    v text;
BEGIN
    v := to_char(t::timestamp + delta, 'YYYY-MM-DD HH24:MI:SS');
    IF length(v) <> 19 THEN
        RETURN NULL;
    END IF;
    RETURN v;
EXCEPTION WHEN OTHERS THEN
    RETURN NULL;
END
$$;

